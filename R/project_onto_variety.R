#' Projection onto a Variety
#'
#' An R-based implementation of gradient-descent homotopies with adaptive step
#' sizes for Euler prediction. The Lagrange version uses Newton's method on the
#' Lagrangian system.
#'
#'
#' @param x0 A numeric vector giving one point to be projected, or a numeric
#'   matrix/data frame whose rows are points to be projected.
#' @param poly An `mpoly` object, typically created with [mpoly::mp()].
#' @param dt The t-mesh size for the homotopy.
#' @param varorder A character vector giving the variable order of the
#'   coordinates of `x0` (default: the sorted variables of `poly`).
#' @param n_correct The number of Newton correction iterations to use.
#' @param al A numeric vector of length 2; the deterministic patch to do
#'   projective calculations over.
#' @param tol A tolerance on the residual; a warning is issued if the magnitude
#'   of the residual is larger than `tol`.
#' @param tol_x A tolerance on subsequent step sizes.
#' @param method Used in [project_onto_variety_lagrange()],
#'   [project_onto_variety_gradient_descent()], and
#'   [project_onto_variety_newton()]. In the Lagrange method, if
#'   `"newton"`, a simple R implementation of Newton's method to solve the
#'   nonlinear algebraic system generated by the Lagrangian; otherwise, a
#'   character string to pass to [stats::optim()] to minimize
#'   the sum of the squares of the Lagrangian. In the gradient-descent and
#'   Newton methods, `method` controls the line-search/fixed-step update:
#'   `"line"` (line search), `"optimal"`, or `"fixed"`.
#' @param maxit Number of maximum iterations in solving Newton's method.
#' @param ga Learning rate for gradient descent.
#' @param max_ga Maximum learning rate for gradient descent line search.
#' @param message If `TRUE`, the user is issued messages on the algorithm's
#'   progress.
#' @param ... Additional arguments to pass to [stats::optim()] when `method` is
#'   not `"newton"`.
#' @param gfunc,dgfunc,ddgfunc The polynomial [poly], its gradient, and its
#'   Hessian as functions. Only used in [project_onto_variety()], and computed
#'   internally if not provided.
#' @param bias A multiple to add to the identity to make the Jacobian
#'   invertible.
#' @param adaptive Defaults to `TRUE`. Whether to use adaptive step sizes.
#' @param dt_min,dt_max Minimum and maximum allowed step sizes during adaptive
#'   integration (default: `1e-6` and `0.1`).
#' @param error_tol Tolerance used for adaptive step size control
#'   (default: `0.01`). Smaller values give more accurate results at the cost of
#'   runtime.
#' @return If `x0` is a vector, a numeric vector the same length as `x0`. If
#'   `x0` is a matrix/data frame, a matrix/data frame of projected points with
#'   the same number of rows.
#' @references Griffin, Z. and J. Hauenstein (2015). Real solutions to systems
#'   of polynomial equations and parameter continuation. \emph{Advances in
#'   Geometry} 15(2), pp.173--187.
#' @references Bates, D., J. Hauenstein, A. Sommese, and C. Wampler (2013).
#'   Numerically Solving Polynomial Systems with Bertini. SIAM. pp.34--35.
#' @author David Kahle
#' @name project-onto-variety
#' @examples
#'
#' library("ggplot2")
#' library("mpoly")
#'
#' \dontrun{
#' # basic usage
#' x0 <- c(1, 1)
#' p1 <- mp("x^2 + y^2 - 1")
#' x1_proj <- project_onto_variety(x0, p1)
#' x1_proj
#'
#' # residual on the variety should be near zero
#' as.function(p1)(x1_proj)
#'
#' df1 <- data.frame(
#'   x = x0[1], y = x0[2],
#'   x_proj = x1_proj[1], y_proj = x1_proj[2]
#' )
#' ggplot() +
#'   geom_variety(poly = p1, xlim = c(-2, 2), ylim = c(-2, 2)) +
#'   geom_segment(aes(x, y, xend = x_proj, yend = y_proj), data = df1) +
#'   coord_equal()
#'
#'
#'
#' # adaptive time stepping (default) versus fixed step size
#' x2_adapt <- project_onto_variety(x0, p1)
#' x2_fixed <- project_onto_variety(x0, p1, adaptive = FALSE, dt = 0.01)
#' x2_strict <- project_onto_variety(x0, p1, error_tol = 0.001)
#'
#' rbind(
#'   adaptive = x2_adapt,
#'   fixed = x2_fixed,
#'   adaptive_strict = x2_strict
#' )
#'
#'
#'
#' # optionally inspect adaptive step messages
#' project_onto_variety(x0, p1, message = TRUE)
#'
#'
#'
#' # precomputing polynomial/gradient/hessian functions
#' varorder <- c("x", "y")
#' gfunc <- as.function(p1, varorder = varorder)
#' dg <- stats::deriv(p1, var = varorder)
#' dgfunc <- as.function(dg, varorder = varorder)
#' ddg <- lapply(dg, stats::deriv, var = varorder)
#' ddgfunc_list <- lapply(ddg, as.function, varorder = varorder, silent = TRUE)
#' ddgfunc <- function(x) sapply(ddgfunc_list, function(f) f(x))
#' project_onto_variety(x0, p1, gfunc = gfunc, dgfunc = dgfunc, ddgfunc = ddgfunc)
#'
#'
#'
#' # projecting multiple points (matrix or data frame input)
#' x2 <- rbind(c(1, 1), c(-1, 0.3), c(0.2, -1.3))
#' project_onto_variety(x2, p1)
#' project_onto_variety(as.data.frame(x2), p1)
#'
#'
#'
#' # alternative projection methods
#' project_onto_variety_lagrange(x0, p1)
#' project_onto_variety_newton(x0, p1)
#' project_onto_variety_gradient_descent(x0, p1, method = "line")
#' project_onto_variety_gradient_descent(x0, p1, method = "optimal")
#' project_onto_variety_gradient_descent(x0, p1, method = "fixed")
#'
#'
#'
#' # naive usages / method comparison on a small grid
#' # (gradient descent methods minimize g(x)^2 directly)
#' library("dplyr")
#' set.seed(1)
#' grid <- expand.grid(x = seq(-1, 1, by = 0.5), y = seq(-1, 1, by = 0.5))
#' grid$x <- jitter(grid$x)
#' grid$y <- jitter(grid$y)
#'
#' proj_homotopy <- project_onto_variety(grid, p1)
#' proj_gd_opt <- project_onto_variety_gradient_descent(grid, p1, method = "optimal")
#' proj_newton <- project_onto_variety_newton(grid, p1)
#'
#' names(proj_homotopy) <- c("x_proj", "y_proj")
#' names(proj_gd_opt) <- c("x_proj", "y_proj")
#' names(proj_newton) <- c("x_proj", "y_proj")
#'
#' df_cmp <- bind_rows(
#'   bind_cols(grid, proj_homotopy) |> mutate(method = "homotopy (adaptive default)"),
#'   bind_cols(grid, proj_gd_opt)   |> mutate(method = "naive gd on g^2 (optimal)"),
#'   bind_cols(grid, proj_newton)   |> mutate(method = "newton on g^2")
#' )
#'
#' ggplot() +
#'   geom_variety(poly = p1, xlim = c(-1.2, 1.2), ylim = c(-1.2, 1.2)) +
#'   geom_segment(
#'     aes(x, y, xend = x_proj, yend = y_proj),
#'     data = df_cmp, inherit.aes = FALSE, alpha = 0.6
#'   ) +
#'   geom_point(aes(x, y), data = grid, inherit.aes = FALSE, size = 0.8) +
#'   coord_equal() +
#'   facet_wrap(~ method)
#'
#'
#'
#' # changing adaptive control parameters
#' project_onto_variety(
#'   x0, p1,
#'   adaptive = TRUE,
#'   dt = 0.05,
#'   dt_min = 1e-5,
#'   dt_max = 0.2,
#'   error_tol = 0.005,
#'   message = TRUE
#' )
#'
#'
#'
#' # more complex curve
#' p_complex <- mp("(x^2 + y^2)^2 - 2 * (x^2 - y^2)")
#' x_complex <- c(1, 1)
#' x_complex_proj <- project_onto_variety(x_complex, p_complex)
#' df_complex <- data.frame(
#'   x = x_complex[1], y = x_complex[2],
#'   x_proj = x_complex_proj[1], y_proj = x_complex_proj[2]
#' )
#' ggplot() +
#'   geom_variety(poly = p_complex, xlim = c(-2, 2), ylim = c(-2, 2)) +
#'   geom_segment(aes(x, y, xend = x_proj, yend = y_proj), data = df_complex) +
#'   coord_equal()
#'
#'
#'
#' # projecting a sample from rvnorm (batch usage)
#' # cut down on draws for example runtime
#' samps <- rvnorm(500, p1, sd = 0.05, output = "tibble")
#' idx <- sample(seq_len(nrow(samps)), size = min(75, nrow(samps)))
#' subsamps <- samps[idx, , drop = FALSE]
#' proj_sub <- project_onto_variety(subsamps[, c("x", "y")], p1)
#' names(proj_sub) <- c("x_proj", "y_proj")
#' df_sub <- dplyr::bind_cols(subsamps, proj_sub)
#'
#' ggplot(df_sub, aes(x, y)) +
#'   geom_segment(aes(xend = x_proj, yend = y_proj), alpha = 0.4) +
#'   geom_point(size = 0.8) +
#'   geom_variety(poly = p1, xlim = c(-2, 2), ylim = c(-2, 2), inherit.aes = FALSE) +
#'   coord_equal()
#'
#'
#'
#' # higher-dimensional example
#' x3 <- c(1, 1, 1)
#' p2 <- mp("x^2 + y^2 + z^2 - 1")
#' project_onto_variety(x3, p2)
#' }




#' @rdname project-onto-variety
#' @export
project_onto_variety <- function(
    x0, poly, dt = .01, varorder = sort(mpoly::vars(poly)),
    n_correct = 2, al = c(1, 1),
    message = FALSE, tol = .Machine$double.eps^(1/2),
    gfunc, dgfunc, ddgfunc, bias = 0,
    adaptive = TRUE,
    dt_min = 1e-6, dt_max = 0.1, error_tol = .01
) {
  # homotopy from t=1 (x0 offset equation) to t=0 (target variety equation)
  t_start <- 1
  t_end <- 0
  if (missing(x0)) stop("`x0` must be supplied.")
  if (missing(poly)) stop("`poly` must be supplied.")
  if (length(mpoly::vars(poly)) == 0L) {
    stop("`poly` must contain at least one variable.", call. = FALSE)
  }
  if (!is.numeric(al) || length(al) < 2 || any(!is.finite(al[1:2]))) {
    stop("`al` must be a numeric vector with at least two finite entries.")
  }
  if (!is.numeric(dt) || length(dt) != 1L || !is.finite(dt) || dt <= 0) {
    stop("`dt` must be a positive finite numeric scalar.", call. = FALSE)
  }
  if (
    !is.numeric(n_correct) || length(n_correct) != 1L ||
      !is.finite(n_correct) || n_correct < 0 || n_correct != as.integer(n_correct)
  ) {
    stop("`n_correct` must be a non-negative integer.", call. = FALSE)
  }
  n_correct <- as.integer(n_correct)
  if (!is.logical(message) || length(message) != 1L || is.na(message)) {
    stop("`message` must be TRUE or FALSE.", call. = FALSE)
  }
  if (!is.numeric(tol) || length(tol) != 1L || !is.finite(tol) || tol <= 0) {
    stop("`tol` must be a positive finite numeric scalar.", call. = FALSE)
  }
  if (!is.numeric(bias) || length(bias) != 1L || !is.finite(bias)) {
    stop("`bias` must be a finite numeric scalar.", call. = FALSE)
  }
  if (!is.logical(adaptive) || length(adaptive) != 1L || is.na(adaptive)) {
    stop("`adaptive` must be TRUE or FALSE.", call. = FALSE)
  }
  if (
    !is.numeric(dt_min) || length(dt_min) != 1L ||
      !is.finite(dt_min) || dt_min <= 0
  ) {
    stop("`dt_min` must be a positive finite numeric scalar.", call. = FALSE)
  }
  if (
    !is.numeric(dt_max) || length(dt_max) != 1L ||
      !is.finite(dt_max) || dt_max < dt_min
  ) {
    stop("`dt_max` must be finite and greater than or equal to `dt_min`.", call. = FALSE)
  }
  if (
    !is.numeric(error_tol) || length(error_tol) != 1L ||
      !is.finite(error_tol) || error_tol <= 0
  ) {
    stop("`error_tol` must be a positive finite numeric scalar.", call. = FALSE)
  }


  # build polynomial, jacobian, and hessian function handles when not supplied
  if (missing(gfunc) || missing(dgfunc) || missing(ddgfunc)) {

    if (!missing(gfunc) || !missing(dgfunc) || !missing(ddgfunc)) {
      # if one derivative helper is missing, rebuild all three consistently
      warning(
        "If any of `gfunc`, `dgfunc`, or `ddgfunc` is not provided,",
        " they are all computed internally.",
        call. = FALSE
      )
    }

    # polynomial, jacobian, and hessian as functions of a point
    gfunc <- poly_function(poly, varorder = varorder)
    dgfunc <- gradient_function(poly, varorder)
    ddgfunc <- hessian_function(poly, varorder)

  }


  # vectorized convenience path for row-wise projection of matrices/data frames
  if (is.matrix(x0) || is.data.frame(x0)) {
    x0_mat <- as.matrix(x0)
    if (!is.numeric(x0_mat) || any(!is.finite(x0_mat))) {
      stop("`x0` must be finite numeric.", call. = FALSE)
    }
    if (ncol(x0_mat) != length(varorder)) {
      stop("`x0` must have one column per variable in `varorder`.", call. = FALSE)
    }
    out <- apply(
      x0_mat, 1, project_onto_variety,
      poly = poly, dt = dt, varorder = varorder, n_correct = n_correct,
      al = al, message = message, tol = tol,
      gfunc = gfunc, dgfunc = dgfunc, ddgfunc = ddgfunc,
      bias = bias, adaptive = adaptive,
      dt_min = dt_min, dt_max = dt_max, error_tol = error_tol
    )
    out <- projected_rows(out, x0_mat)
    if (is.data.frame(x0)) out <- as.data.frame(out)
    if (inherits(x0, "tbl_df")) class(out) <- c("tbl_df", "tbl", "data.frame")
    return(out)
  }

  # main computation for one starting point x0
  n_vars <- length(varorder)
  if (!is.numeric(x0) || length(x0) != n_vars || any(!is.finite(x0))) {
    stop("`x0` must be a finite numeric vector with one entry per variable.", call. = FALSE)
  }

  vn <- c(x0, al[1], 0)

  Ha <- function(v, t) {
    # augmented homotopy system in (x, lambda0, lambda1)
    x <- v[1:n_vars]; la <- v[-(1:n_vars)]
    c(
      gfunc(x) - t*gfunc(x0),
      as.numeric(cbind((x-x0), dgfunc(x)) %*% la),
      la[1] + la[2]*al[2] - al[1]
    )
  }
  # ha(vn, .99)

  JHa <- function(v, t) {
    x <- v[1:n_vars]
    la0 <- v[n_vars+1]
    la1 <- v[n_vars+2]
    al1 <- al[2]
    rbind(
      c(dgfunc(x), 0, 0),
      cbind(
        la0*diag(n_vars) + la1*ddgfunc(x),
        x - x0,
        dgfunc(x)
      ),
      c(rep(0, n_vars), 1, al1)
    )
  }
  # jHa(vn, .99)

  # partial derivative of H w.r.t t:
  Ht <- function(v, t) c(-gfunc(x0), rep(0, n_vars + 2 - 1))
  # ht(c(1,1), 1)

  if (adaptive) {
    # adaptive predictor-corrector (Euler + Heun) with error control
    t <- t_start
    while (t > t_end) {
      h <- min(dt, t - t_end)

      # predictor: Euler step
      F1 <- solve(JHa(vn, t), Ht(vn, t))
      v_euler <- vn + h * F1

      # corrector: Heun step
      F2 <- solve(JHa(v_euler, t - h), Ht(v_euler, t - h))
      v_heun <- vn + 0.5 * h * (F1 + F2)

      err <- sqrt(sum((v_heun - v_euler)^2))

      if (err < error_tol) {
        # accept step and perform Newton corrections on the new time slice
        vn <- v_heun
        t <- t - h

        for (. in seq_len(n_correct)) {
          vn <- vn - solve(JHa(vn, t) + bias * diag(n_vars + 2), Ha(vn, t))
        }

        if (message) message("t: ", round(t, 5), " | dt: ", round(h, 5))

        dt <- min(dt_max, h * min(2, (error_tol / err)^0.5))
      } else {
        # reject step and shrink dt
        if (h <= dt_min || dt <= dt_min) {
          stop(
            "Adaptive projection failed to meet `error_tol` at `dt_min`.",
            call. = FALSE
          )
        }
        dt <- max(dt_min, h * max(0.1, (error_tol / err)^0.5))
        if (message) message("  Rejected step. Reducing dt to ", round(dt, 6))
      }
    }

  } else {
    # fixed-step predictor + Newton-corrector path
    ts <- seq(t_start, t_end, -dt)
    if (!identical(ts[length(ts)], t_end)) {
      ts <- c(ts, t_end)
    }
    for (i in 2:length(ts)) {
      h <- ts[i - 1] - ts[i]
      vn <- vn + solve(JHa(vn, t = ts[i - 1]), Ht(vn, t = ts[i - 1])) * h
      if (message) message(paste(round(vn, 5), collapse = " "))

      for (. in seq_len(n_correct)) {
        vn <- vn - solve(
          JHa(vn, t = ts[i]) + bias * diag(n_vars + 2),
          Ha(vn, t = ts[i])
        )
        if (message) message("  ", paste(round(vn, 5), collapse = " "))
      }
    }
  }

  resid <- gfunc(vn[1:n_vars])
  if (abs(resid) >= tol) {
    warning(
      sprintf("Tolerance not met (residual = %.2e).", resid),
      call. = FALSE
    )
  }
  vn[1:n_vars]
}




#' @rdname project-onto-variety
#' @export
project_onto_variety_lagrange <- function(
    x0, poly, varorder = sort(mpoly::vars(poly)), method = "newton", maxit = 1e3,
    tol = .Machine$double.eps^(1/2), tol_x = .Machine$double.eps^(1/2),
    message = FALSE, ...
  ) {
  # solve KKT stationarity system for closest-point projection
  if (length(mpoly::vars(poly)) == 0L) {
    stop("`poly` must contain at least one variable.", call. = FALSE)
  }

  # vectorized convenience path for row-wise projection
  if (is.matrix(x0) || is.data.frame(x0)) {
    out <- apply(
      x0, 1, project_onto_variety_lagrange,
      poly = poly, varorder = varorder, method = method, maxit = maxit,
      tol = tol, tol_x = tol_x,
      message = message, ...
    )
    out <- projected_rows(out, x0)
    if (is.data.frame(x0)) out <- as.data.frame(out)
    if (inherits(x0, "tbl_df")) class(out) <- c("tbl_df", "tbl", "data.frame")
    return(out)
  }

  # build Lagrangian and stationarity equations; arithmetic on x0 itself, as
  # printing it into a formula would round it to 15 significant digits
  L <- Reduce(`+`, Map(function(var, x) (mp(var) - x)^2, varorder, x0)) +
    mp("la")*poly
  dL <- stats::deriv(L, var = c(varorder, "la"))
  dLf <- poly_function(dL, varorder = c(varorder, "la"))

  if (method == "newton") {

    ddL <- lapply(dL, stats::deriv, var = c(varorder, "la"))
    ddLf <- lapply(
      ddL,
      poly_function,
      varorder = c(varorder, "la")
    )
    H <- function(v) do.call(rbind, lapply(ddLf, function(f) f(v)))

    # initialize Lagrange multiplier by minimizing stationarity residual
    la0 <- stats::optimize(
      function(.) sum(dLf(c(x0, .))^2),
      lower = 0,
      upper = 1e3
    )$minimum

    xn_1 <- c(x0, la0)
    xn <- xn_1 + solve( H(xn_1), -dLf(xn_1) )

    count <- 0L
    while (
      sum(abs(dLf(xn))) > tol &&
      sum(abs(xn - xn_1)) > tol_x &&
      count < maxit
    ) {
      xn_1 <- xn
      xn <- xn_1 + solve( H(xn_1), -dLf(xn_1) )
      if (message) message(paste(round(xn, 5), collapse = " "))
      count <- count + 1L
    }
    xn <- xn[seq_along(varorder)]

  } else {

    la0 <- optimize(
      function(.) sum(dLf(c(x0, .))^2),
      lower = 0,
      upper = 1e3
    )$minimum
    xn <- stats::optim(
      c(x0, la0),
      function(.) sum(dLf(.)^2),
      method = method,
      ...
    )$par[seq_len(length(varorder))]

  }

  pf  <- poly_function(poly, varorder = varorder)
  resid <- pf(xn)
  if (abs(resid) >= tol) {
    warning(
      sprintf("Tolerance not met (residual = %.2e).", resid),
      call. = FALSE
    )
  }

  xn

}







#' @rdname project-onto-variety
#' @export
project_onto_variety_gradient_descent <- function(
    x0, poly, varorder = sort(mpoly::vars(poly)), ga = .01, max_ga = .1,
    method = c("line", "optimal", "fixed"),
    tol = .Machine$double.eps^(1/2), tol_x = .Machine$double.eps^(1/2),
    maxit = 1e3, message = FALSE
) {
  # minimize g(x)^2 using gradient descent variants
  if (length(mpoly::vars(poly)) == 0L) {
    stop("`poly` must contain at least one variable.", call. = FALSE)
  }

  # vectorized convenience path for row-wise projection
  if (is.matrix(x0) || is.data.frame(x0)) {
    out <- apply(
      x0, 1, project_onto_variety_gradient_descent,
      poly = poly,
      varorder = varorder,
      ga = ga,
      max_ga = max_ga,
      method = method,
      tol = tol, tol_x = tol_x,
      maxit = maxit, message = message
    )
    out <- projected_rows(out, x0)
    if (is.data.frame(x0)) out <- as.data.frame(out)
    if (inherits(x0, "tbl_df")) class(out) <- c("tbl_df", "tbl", "data.frame")
    return(out)
  }

  # validate and dispatch descent strategy
  method <- match.arg(method)

  # build objective and gradient helpers for g(x)^2
  pf  <- poly_function(poly, varorder = varorder)
  p2f <- poly_function(poly^2, varorder = varorder)
  dp2f <- gradient_function(poly^2, varorder)


  if (method == "optimal") {

    xn_2 <- x0

    direction_2 <- dp2f(xn_2)
    ga <- stats::optimize(
      function(.) p2f(xn_2 - . * direction_2),
      lower = 0,
      upper = max_ga
    )$minimum
    xn_1 <- xn_2 - ga*direction_2
    if (message) message(paste(round(xn_1, 5), collapse = " "))

    direction_1 <- dp2f(xn_1)
    ga <- stats::optimize(
      function(.) p2f(xn_1 - . * direction_1),
      lower = 0,
      upper = max_ga
    )$minimum
    xn <- xn_1 - ga*direction_1
    if (message) message(paste(round(xn, 5), collapse = " "))

    count <- 0
    while (abs(pf(xn)) > tol && sum(abs(xn-xn_1)) > tol_x && count < maxit) {
      xn_2 <- xn_1
      xn_1 <- xn
      direction_2 <- dp2f(xn_2)
      direction_1 <- dp2f(xn_1)
      # step size from successive Barzilai-Borwein gradient differences
      denom <- sum((direction_1 - direction_2)^2)
      ga <- if (denom > 0) {
        abs(sum((xn_1 - xn_2) * (direction_1 - direction_2))) / denom
      } else {
        max_ga
      }
      xn   <- xn_1 - ga*direction_1
      count <- count + 1
      if (message) message(paste(round(xn, 5), collapse = " "))
    }

  } else if (method == "line") {

    xn_1 <- x0

    direction <- dp2f(xn_1)
    ga <- stats::optimize(
      function(.) p2f(xn_1 - . * direction),
      lower = 0,
      upper = max_ga
    )$minimum
    xn <- xn_1 - ga*dp2f(xn_1)
    if (message) message(paste(round(xn, 5), collapse = " "))

    count <- 0
    while (abs(pf(xn)) > tol && sum(abs(xn-xn_1)) > tol_x && count < maxit) {
      xn_1 <- xn
      direction <- dp2f(xn_1)
      ga <- stats::optimize(
        function(.) p2f(xn_1 - . * direction),
        lower = 0,
        upper = max_ga
      )$minimum
      xn   <- xn_1 - ga*direction
      count <- count + 1
      if (message) message(paste(round(xn, 5), collapse = " "))
    }

  } else if (method == "fixed") {

    xn_1 <- x0

    direction <- dp2f(xn_1)
    xn <- xn_1 - ga*direction
    if (message) message(paste(round(xn, 5), collapse = " "))

    count <- 0
    while (abs(pf(xn)) > tol && sum(abs(xn-xn_1)) > tol_x && count < maxit) {
      xn_1 <- xn
      direction <- dp2f(xn_1)
      xn   <- xn_1 - ga*direction
      count <- count + 1
      if (message) message(paste(round(xn, 5), collapse = " "))
    }

  }

  resid <- pf(xn)
  if (abs(resid) >= tol) {
    warning(
      sprintf("Tolerance not met (residual = %.2e).", resid),
      call. = FALSE
    )
  }

  xn
}








#' @rdname project-onto-variety
#' @export
project_onto_variety_newton <- function(
    x0, poly, varorder = sort(mpoly::vars(poly)), ga = 1e-4, max_ga = 2,
    method = c("line", "fixed"),
    tol = .Machine$double.eps^(1/2), tol_x = .Machine$double.eps^(1/2),
    maxit = 1e3, message = FALSE
) {
  # minimize g(x)^2 with Newton updates and optional line search
  if (length(mpoly::vars(poly)) == 0L) {
    stop("`poly` must contain at least one variable.", call. = FALSE)
  }

  # vectorized convenience path for row-wise projection
  if (is.matrix(x0) || is.data.frame(x0)) {
    out <- apply(
      x0, 1, project_onto_variety_newton,
      poly = poly, varorder = varorder, ga = ga, max_ga = max_ga,
      method = method, tol = tol, tol_x = tol_x,
      maxit = maxit, message = message
    )
    out <- projected_rows(out, x0)
    if (is.data.frame(x0)) out <- as.data.frame(out)
    if (inherits(x0, "tbl_df")) class(out) <- c("tbl_df", "tbl", "data.frame")
    return(out)
  }

  # validate method option
  method <- match.arg(method)

  # build objective, gradient, and hessian helpers for g(x)^2
  pf  <- poly_function(poly, varorder = varorder)
  p2f <- poly_function(poly^2, varorder = varorder)
  dp2f <- gradient_function(poly^2, varorder)
  ddp2f <- hessian_function(poly^2, varorder)

  # the hessian of g^2 is singular where g = 0 has flat directions (for a
  # linear g, everywhere), so take the minimum-norm least-squares newton step
  # there. Its gradient can leave the hessian's column space, where scaling
  # rows (as pdvnorm_pseudoinverse() does) would change the step
  newton_direction <- function(v) {
    as.numeric(svd_pseudoinverse(ddp2f(v)) %*% -dp2f(v))
  }

  # iterative Newton updates
  xn_1 <- x0

  direction <- newton_direction(xn_1)
  if (method == "line") {
    ga <- stats::optimize(
      function(.) p2f(xn_1 + . * direction),
      lower = 0,
      upper = max_ga
    )$minimum
  }
  xn <- xn_1 + ga*direction
  if (message) message(paste(round(xn, 5), collapse = " "))

  count <- 0
  while (abs(pf(xn)) > tol && sum(abs(xn-xn_1)) > tol_x && count < maxit) {
    xn_1 <- xn
    direction <- newton_direction(xn_1)
    if (method == "line") {
      ga <- stats::optimize(
        function(.) p2f(xn_1 + . * direction),
        lower = 0,
        upper = max_ga
      )$minimum
    }
    xn   <- xn_1 + ga*direction
    count <- count + 1
    if (message) message(paste(round(xn, 5), collapse = " "))
  }


  resid <- pf(xn)
  if (abs(resid) >= tol) {
    warning(
      sprintf("Tolerance not met (residual = %.2e).", resid),
      call. = FALSE
    )
  }

  xn
}




projected_rows <- function(out, x0) {
  # apply() returns one column per projected point, or a plain vector when
  # points have a single coordinate, which t() would make a single row
  x0 <- as.matrix(x0)
  matrix(
    out, nrow = nrow(x0), ncol = ncol(x0), byrow = TRUE,
    dimnames = dimnames(x0)
  )
}

project_rows_closest <- function(
    x, poly, varorder, tol = 1e-10, maxit = 100L, max_dist = Inf, scale = 1
  ) {
  # the closest point on the variety of poly (an mpoly or mpolyList) to each
  # row of x, for points near it: Gauss-Newton steps u <- u - J^+ g(u) onto
  # the variety, then steps along its tangent space toward the row, each
  # followed by Gauss-Newton again, until x - u is normal to the variety.
  # Gauss-Newton alone lands a distance O(d^2) along the variety from the
  # closest point, d the distance to it, by an amount that depends on how
  # poly is written. Returns the points, whether each converged, and each
  # row's residual |J^+ g(x)|: a row fails if J loses rank on the way (as
  # at a singular point), it does not converge, it ends more than max_dist
  # from its start, or some equation does not vanish there. Gauss-Newton
  # converges only linearly onto a repeated factor, hence the iterations.
  # Variables in varorder that poly does not involve have zero Jacobian
  # columns, so their coordinates stay put.
  #
  # Tolerances are distances: tol * scale, scale the problem's (the
  # pilot's sd), plus the rounding error of poly's own coordinates. Grown
  # with |u|, they let a translated empty variety pass (x - 1e9 and
  # x - 1e9 - 1 at 1e9 + 0.5), as did a free coordinate far away
  poly_cols <- which(varorder %in% mpoly::vars(poly))
  coordinate_rounding <- function(u) {
    8 * .Machine$double.eps * sqrt(rowSums(u[, poly_cols, drop = FALSE]^2))
  }
  # g within the rounding error of its terms is on the variety as far as can
  # be told, even where the gradient vanishes too, as everywhere on a
  # repeated factor. Closer in, a step of rounding error over a vanishing
  # gradient would throw u off: on (x^2 + y^2 - 1)^3, across the circle
  rounding <- function(g_abs) 64 * .Machine$double.eps * g_abs
  if (is.mpoly(poly)) {
    # one equation, all rows at once: J^+ g = g grad(g) / |grad(g)|^2
    g_fn <- poly_function(poly, varorder = varorder)
    g_abs_fn <- poly_function(abs_coefficients(poly), varorder = varorder)
    dg_fn <- gradient_function(poly, varorder)
    step_fn <- function(u) {
      g <- g_fn(u)
      dg <- matrix(dg_fn(u), nrow = nrow(u))
      dg2 <- rowSums(dg^2)
      on_variety <- is.finite(g) & abs(g) <= rounding(g_abs_fn(abs(u)))
      stalled <- !is.finite(g) | (!(dg2 > 0) & !on_variety)
      step <- g / dg2 * dg
      step[stalled | on_variety, ] <- 0
      list(step = step, stalled = stalled)
    }
    dg_abs_fn <- gradient_function(abs_coefficients(poly), varorder)
    tangent_fn <- function(u, r) {
      # the gradient is known only above the rounding error of its terms;
      # where it is not (on the variety of a cube such as (x^2 + y^2 - 1)^3,
      # about 6e-18) the tangent space is unknown, so u stays
      dg <- matrix(dg_fn(u), nrow = nrow(u))
      dg2 <- rowSums(dg^2)
      dg_abs <- matrix(dg_abs_fn(abs(u)), nrow = nrow(u))
      known <- sqrt(dg2) > 1e3 * .Machine$double.eps * sqrt(rowSums(dg_abs^2))
      tangent <- r - rowSums(r * dg) / dg2 * dg
      tangent[!known, ] <- 0
      tangent
    }
  } else {
    g_fn <- poly_function(poly, varorder = varorder)
    g_abs_fn <- poly_function(
      structure(lapply(poly, abs_coefficients), class = "mpolyList"),
      varorder = varorder
    )
    J_fn <- jacobian_function(poly, varorder)
    # variables poly does not involve add zero columns, which cannot raise
    # J's rank; its pseudoinverse uses poly's own columns
    full_rank <- min(length(poly), length(mpoly::vars(poly)))
    poly_cols <- which(varorder %in% mpoly::vars(poly))
    step_fn <- function(u) {
      step <- matrix(0, nrow(u), ncol(u))
      stalled <- logical(nrow(u))
      for (i in seq_len(nrow(u))) {
        g <- g_fn(u[i, ])
        # on the variety as far as can be told, whatever J's rank there
        if (all(is.finite(g)) && all(abs(g) <= rounding(g_abs_fn(abs(u[i, ]))))) next
        Jp <- pdvnorm_pseudoinverse_cols(J_fn(u[i, ]), poly_cols)
        s <- as.numeric(Jp %*% g)
        if (attr(Jp, "rank") < full_rank || any(!is.finite(s))) {
          stalled[i] <- TRUE
        } else {
          step[i, ] <- s
        }
      }
      list(step = step, stalled = stalled)
    }
    tangent_fn <- function(u, r) {
      # remove the component of r in J's row space, the normal space; where
      # J vanishes the tangent space is unknown, so u stays
      for (i in seq_len(nrow(u))) {
        J <- J_fn(u[i, ])
        r[i, ] <- if (all(J == 0)) {
          0
        } else {
          r[i, ] - as.numeric(pdvnorm_pseudoinverse_cols(J, poly_cols) %*% (J %*% r[i, ]))
        }
      }
      r
    }
  }
  small <- function(v, u) sqrt(rowSums(v^2)) <= tol * scale + coordinate_rounding(u)

  newton <- function(u) {
    ok <- rep(FALSE, nrow(u))
    active <- seq_len(nrow(u))
    for (. in seq_len(maxit)) {
      ua <- u[active, , drop = FALSE]
      s <- step_fn(ua)
      u[active, ] <- ua - s$step
      done <- !s$stalled & small(s$step, ua)
      ok[active[done]] <- TRUE
      active <- active[!done & !s$stalled]
      if (length(active) == 0L) break
    }
    list(u = u, ok = ok)
  }

  residual <- sqrt(rowSums(step_fn(x)$step^2))
  first <- newton(x)
  u <- first$u
  ok <- first$ok
  # the closest-point refinement needs the tangent space, which a repeated
  # factor's gradient cannot give: it vanishes on the variety and comes from
  # cancelling terms near it. There the residual is about the distance / k
  # for k > 1 (see rvnorm_domain_latent()), and Gauss-Newton's point
  # stands. Its steps follow the reduced factor's gradient, so it lands
  # within O(d^2) of the closest point
  simple <- sqrt(rowSums((u - x)^2)) <= 1.5 * residual
  converged <- ok & !simple
  active <- which(ok & simple)
  for (. in seq_len(maxit)) {
    if (length(active) == 0L) break
    ua <- u[active, , drop = FALSE]
    tangent <- tangent_fn(ua, x[active, , drop = FALSE] - ua)
    at_closest <- small(tangent, ua)
    converged[active[at_closest]] <- TRUE
    moving <- active[!at_closest]
    if (length(moving) == 0L) break
    again <- newton(u[moving, , drop = FALSE] + tangent[!at_closest, , drop = FALSE])
    u[moving, ] <- again$u
    ok[moving] <- again$ok
    active <- moving[again$ok]
  }

  ok <- ok & converged & rowSums(!is.finite(u)) == 0 &
    sqrt(rowSums((u - x)^2)) <= max_dist
  # a vanishing step does not put u on the variety: for an overdetermined
  # system it also vanishes at least-squares points where g does not, and
  # for an empty variety only there
  ok[ok] <- variety_feasible(
    u[ok, , drop = FALSE], poly, varorder,
    1e-6 * scale + coordinate_rounding(u[ok, , drop = FALSE])
  )
  list(points = u, ok = ok, residual = residual)
}

variety_feasible <- function(u, poly, varorder, dist) {
  # whether each row of u lies on the variety: every equation g_i vanishes
  # there to within the distance dist, |g_i| <= dist |grad g_i|, or to
  # rounding error in its terms, which covers points where grad g_i
  # vanishes too
  polys <- if (is.mpoly(poly)) list(poly) else unclass(poly)
  ok <- rep(TRUE, nrow(u))
  for (g in polys) {
    g_val <- poly_function(g, varorder = varorder)(u)
    grad <- matrix(gradient_function(g, varorder)(u), nrow = nrow(u))
    g_abs <- poly_function(abs_coefficients(g), varorder = varorder)(abs(u))
    ok <- ok & is.finite(g_val) &
      abs(g_val) <= dist * sqrt(rowSums(grad^2)) +
        64 * .Machine$double.eps * g_abs
  }
  ok
}

abs_coefficients <- function(p) {
  # p with each coefficient replaced by its absolute value: evaluated at |u|,
  # the sum of the magnitudes of p's terms at u
  structure(
    lapply(unclass(p), function(term) {
      term[["coef"]] <- abs(term[["coef"]])
      term
    }),
    class = "mpoly"
  )
}
